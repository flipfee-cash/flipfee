// Copies the IDL built by `anchor build` into client/idl/ and generates client/src/generated.ts
// (program id, discriminators, errors) from it. Run after every program change: `npm run idl`.
import { readFileSync, writeFileSync, existsSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const built = join(here, '../../target/idl/flipfee.json');
const kept = join(here, '../idl/flipfee.json');
if (existsSync(built)) copyFileSync(built, kept);
const idl = JSON.parse(readFileSync(kept, 'utf8'));

const disc = (items) =>
  Object.fromEntries(items.map((x) => [x.name, x.discriminator]));
const line = (o) =>
  Object.entries(o)
    .map(([k, v]) => `  ${k}: [${v.join(', ')}],`)
    .join('\n');

const out = `// Generated by client/scripts/gen.mjs from idl/flipfee.json (Anchor ${idl.metadata.spec ? 'IDL spec ' + idl.metadata.spec : ''}). Do not edit.

/** Program id the IDL was built with (declare_id! in programs/flipfee/src/lib.rs). */
export const IDL_ADDRESS = '${idl.address}';

/** 8-byte instruction discriminators (sha256("global:<name>")[0..8]). */
export const IX_DISCRIMINATORS = {
${line(disc(idl.instructions))}
} as const;

/** 8-byte account discriminators (sha256("account:<Name>")[0..8]). */
export const ACCOUNT_DISCRIMINATORS = {
${line(disc(idl.accounts))}
} as const;

/** 8-byte event discriminators (sha256("event:<Name>")[0..8]). */
export const EVENT_DISCRIMINATORS = {
${line(disc(idl.events))}
} as const;

/** Program errors (custom error codes). */
export const PROGRAM_ERRORS = [
${idl.errors.map((e) => `  { code: ${e.code}, name: '${e.name}', msg: ${JSON.stringify(e.msg)} },`).join('\n')}
] as const;
`;
writeFileSync(join(here, '../src/generated.ts'), out);
console.log(`generated client/src/generated.ts from ${existsSync(built) ? 'target/idl/flipfee.json' : 'client/idl/flipfee.json'}`);
