type Vars = Record<string, string | number>;

/** Replaces {name} placeholders; {pf} is always pump.fun. */
export function fill(s: string, vars: Vars = {}): string {
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : k === 'pf' ? copy.pf : m));
}
